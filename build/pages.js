/* Generate site/pages.html — the click-through index of everything in the prototype.

   A review tool, not a page of the site: it carries no global header or footer, and
   build/shell.js skips it for that reason. It is regenerated, never hand-edited, so it
   cannot drift from what is actually on disk.

   Three sources, and where they disagree the file system wins:
     the directory   what pages exist at all
     each <title>    what the page calls itself
     URLS.md         the approved production path and status, generated by urlmap.js

   A page on disk but missing from URLS.md shows up as "not in the URL map" rather than
   being quietly dropped — that gap is the thing worth seeing.

   Run: node build/urlmap.js  →  node build/pages.js  →  node build/check.js
*/
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SITE = path.join(ROOT, 'site');
const SELF = 'pages.html';

/* ── what is on disk ─────────────────────────────────────────────────────── */
const files = fs.readdirSync(SITE).filter(f => f.endsWith('.html') && f !== SELF).sort();

/* ── what the URL map says ───────────────────────────────────────────────── */
const rows = new Map();
fs.readFileSync(path.join(ROOT, 'URLS.md'), 'utf8').split('\n').forEach(line => {
  const m = line.match(/^\|\s*`([^`]+\.html)`\s*\|\s*(.*?)\s*\|\s*(.*?)\s*\|\s*(.*?)\s*\|$/);
  if (m) rows.set(m[1], { url: m[2].replace(/`/g, ''), status: m[3], note: m[4] });
});

/* ── what each page calls itself ─────────────────────────────────────────── */
const read = f => {
  const html = fs.readFileSync(path.join(SITE, f), 'utf8');
  const title = (html.match(/<title>([\s\S]*?)<\/title>/) || [, f])[1]
    .replace(/\s*[|–—-]\s*PlagiarismSearch\s*$/, '')
    .replace(/^PlagiarismSearch\s*[|–—-]\s*/, '').trim();
  const h1 = (html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) || [, ''])[1]
    .replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
  return {
    file: f, title, h1,
    stub: /approved destination in the navigation architecture/i.test(html),
    bytes: fs.statSync(path.join(SITE, f)).size,
    ...(rows.get(f) || { url: '', status: 'not in the URL map', note: '' }),
  };
};
const pages = files.map(read);

/* ── grouping: what someone reviewing the prototype actually wants ───────── */
const GROUPS = [
  ['Homepage', p => /^index/.test(p.file)],
  ['Product',  p => ['ai-detector.html', 'api.html', 'plagiarism-check.html', 'paper-analysis.html',
                     'spell-check.html', 'readability-check.html', 'chat-bot.html'].includes(p.file)],
  ['Integrations', p => /integration|google-add-on|canvas|moodle/.test(p.file)],
  ['Audience', p => /students|teachers|university|organization|educators/.test(p.file)],
  ['Plans, company and content', p => ['prices.html', 'vip.html', 'why-us.html', 'mission.html',
                     'contact-us.html', 'help-center.html', 'blog.html', 'testimonials.html'].includes(p.file)
                     || /^blog-/.test(p.file)],
  ['Account and legal', p => /account|policy|terms|privacy|refund|cookie/.test(p.file)],
  ['By file type and use case', p => /^(pdf|powerpoint|quote-checker|originality-badges|turnitin)/.test(p.file)],
  ['Company and programmes', p => /affiliate|newsroom|scholarship|user-manuals/.test(p.file)],
  ['Design reference', p => /design-system|OLD-design/.test(p.file)],
];
const grouped = [];
const taken = new Set();
GROUPS.forEach(([name, test]) => {
  const list = pages.filter(p => !taken.has(p.file) && test(p));
  list.forEach(p => taken.add(p.file));
  if (list.length) grouped.push([name, list]);
});
const rest = pages.filter(p => !taken.has(p.file));
if (rest.length) grouped.push(['Everything else', rest]);

/* ── markup. The head is borrowed from a real page so the tailwind config is the
      same one every other page carries — check.js counts distinct configs. ──── */
const donor = fs.readFileSync(path.join(SITE, 'help-center.html'), 'utf8');
const head = donor.slice(0, donor.indexOf('<body'));
const bodyTag = donor.slice(donor.indexOf('<body'), donor.indexOf('>', donor.indexOf('<body')) + 1);

const esc = s => String(s).replace(/&(?!(amp|lt|gt|quot|#\d+|rsquo|mdash|nbsp);)/g, '&amp;')
                          .replace(/</g, '&lt;').replace(/>/g, '&gt;');

const badge = p =>
  p.stub                        ? '<span class="pg-tag pg-tag-stub">stub</span>'
  : /out of global nav/.test(p.status) ? '<span class="pg-tag pg-tag-quiet">off nav</span>'
  : '';

const card = p => `        <li>
          <a href="${p.file}" class="pg-card">
            <span class="pg-row">
              <span class="pg-name">${esc(p.title || p.file)}</span>
              ${badge(p)}
            </span>
            ${p.h1 && p.h1 !== p.title ? `<span class="pg-h1">${esc(p.h1)}</span>` : ''}
            <span class="pg-foot">
              <code class="pg-file">${p.file}</code>
              <span class="pg-url">${p.url && p.url !== '—' ? esc(p.url) : '<span class="pg-none">no approved path</span>'}</span>
            </span>
          </a>
        </li>`;

const section = ([name, list]) => `      <section class="mb-10 sm:mb-12 lg:mb-14">
        <div class="flex items-baseline gap-3 mb-4 sm:mb-5">
          <h2 class="text-[15px] sm:text-[16px] lg:text-[17px] font-bold tracking-tight">${esc(name)}</h2>
          <span class="text-[11.5px] font-semibold text-ink-400 nums">${list.length}</span>
          <span class="h-px flex-1 bg-ink-100"></span>
        </div>
        <ul class="grid sm:grid-cols-2 lg:grid-cols-3 gap-3 sm:gap-4">
${list.map(card).join('\n')}
        </ul>
      </section>`;

const stubs = pages.filter(p => p.stub).length;
const unmapped = pages.filter(p => p.status === 'not in the URL map').length;

const html = head.replace(/<title>[\s\S]*?<\/title>/, '<title>Prototype index — every page</title>') + `
<style>
  .pg-card { display:flex; flex-direction:column; gap:.45rem; height:100%;
    border-radius:.875rem; background:#fff; padding:.9rem 1rem;
    box-shadow:0 1px 2px rgba(0,0,0,.04); outline:1px solid rgba(0,0,0,.06);
    transition:outline-color .2s ease, box-shadow .2s ease, transform .2s ease; }
  .pg-card:hover { outline-color:#0991A8; box-shadow:0 6px 20px -8px rgba(0,0,0,.18); transform:translateY(-1px); }
  .pg-row { display:flex; align-items:center; gap:.5rem; }
  .pg-name { font-size:13.5px; font-weight:700; letter-spacing:-.01em; color:#111827; }
  .pg-h1 { font-size:12px; color:#6B7280; line-height:1.45; }
  .pg-foot { display:flex; align-items:center; gap:.5rem; margin-top:auto; padding-top:.45rem;
    border-top:1px solid #F1F2F6; }
  .pg-file { font-size:11px; color:#9CA3AF; font-variant-numeric:tabular-nums; }
  .pg-url { margin-left:auto; font-size:11px; font-weight:600; color:#0991A8; }
  .pg-none { color:#D1D5DB; font-weight:500; }
  .pg-tag { font-size:9.5px; font-weight:700; text-transform:uppercase; letter-spacing:.12em;
    padding:.15rem .4rem; border-radius:.35rem; }
  .pg-tag-stub { background:#FDE5E0; color:#B84431; }
  .pg-tag-quiet { background:#F1F2F6; color:#6B7280; }
  @media (min-width:640px) { .pg-card { border-radius:1rem; } }
</style>
${bodyTag}

<main class="min-h-screen bg-[#F7F9FA] py-10 sm:py-14 lg:py-16">
  <div class="max-w-[1180px] mx-auto px-4 sm:px-6 lg:px-10">

    <div class="mb-8 sm:mb-10 lg:mb-12">
      <div class="text-[10px] sm:text-[10.5px] font-semibold uppercase tracking-[0.22em] text-ink-400 mb-3">Prototype index</div>
      <h1 class="text-[26px] sm:text-[30px] lg:text-[34px] font-extrabold tracking-tightest leading-[1.1] mb-3">Every page in the prototype</h1>
      <p class="text-[13.5px] sm:text-[14.5px] leading-relaxed text-ink-600 max-w-[70ch]">
        ${pages.length} pages on disk, ${stubs} of them placeholders for approved destinations that are not built yet${unmapped ? ', ' + unmapped + ' not in the URL map' : ''}.
        Generated from the directory, each page&rsquo;s own title and <code class="text-[12.5px]">URLS.md</code> &mdash; run
        <code class="text-[12.5px]">node build/pages.js</code> after adding a page.
      </p>
      <p class="text-[12.5px] text-ink-400 mt-3">This index is a review tool and carries no global header or footer, which is why <code class="text-[12px]">shell.js</code> skips it.</p>
    </div>

${grouped.map(section).join('\n\n')}

  </div>
</main>

</body>
</html>
`;

fs.writeFileSync(path.join(SITE, SELF), html);
console.log('  site/' + SELF + ' — ' + pages.length + ' pages, ' +
            grouped.length + ' groups, ' + stubs + ' stubs' +
            (unmapped ? ', ' + unmapped + ' unmapped' : ''));
grouped.forEach(([n, l]) => console.log('    ' + String(l.length).padStart(3) + '  ' + n));
