/* The Cookie consent section of site/design-system.html — the last section of the page
   (Olex, 2026-10-28: "в кінці останнім пунктом").

   The card is not drawn again here: its markup is read from the one place the site takes
   it from, build/shell/footer-v2.html ([data-cookie-consent]), and shown in each of its
   states — so the spec and the site cannot drift apart. Each copy is static: its views are
   set in the markup, its ids made unique, and it is not the live card (the design-system
   page has no site footer, so module cookie-consent finds nothing to run on here).

     node build/design-system-cookies.js

   Splices the section between two markers (after Anti-patterns, before Sources of truth)
   and the nav entry once. Run it again and it replaces itself. */
const fs = require('fs');
const path = require('path');

const FILE = path.join(__dirname, '..', 'site', 'design-system.html');
const TPL = path.join(__dirname, 'shell', 'footer-v2.html');
let html = fs.readFileSync(FILE, 'utf8');
const tpl = fs.readFileSync(TPL, 'utf8');

const START = '      <!-- cookies:start — generated by build/design-system-cookies.js; do not edit by hand -->';
const END = '      <!-- cookies:end -->';

/* the card: the first element inside [data-cookie-consent], up to its closing </div> */
function cardMarkup() {
  const open = tpl.indexOf('<div data-cookie-consent');
  if (open < 0) throw new Error('design-system-cookies: no [data-cookie-consent] in footer-v2.html');
  const from = tpl.indexOf('<div class="relative rounded-', open);
  if (from < 0) throw new Error('design-system-cookies: the card element moved');
  let depth = 0, i = from;
  const re = /<\/?div\b[^>]*>/g;
  re.lastIndex = from;
  let m;
  while ((m = re.exec(tpl))) { depth += m[0][1] === '/' ? -1 : 1; if (depth === 0) { i = re.lastIndex; break; } }
  if (depth !== 0) throw new Error('design-system-cookies: the card never closes');
  return tpl.slice(from, i);
}
const CARD = cardMarkup();

/* one static copy of the card in a view: what belongs to the view is shown, the rest hidden */
function state(view, n, { analytics = false } = {}) {
  let c = CARD.replace(/\sid="(cc-[\w-]+)"/g, (a, id) => ` id="${id}-ds${n}"`);
  c = c.replace(/<(\w+)([^>]*?)\sdata-cc-view="([^"]+)"([^>]*?)>/g, (a, tag, pre, views, post) => {
    const on = views.split(' ').includes(view);
    return `<${tag}${pre.replace(/\shidden(?=[\s>]|$)/g, '')} data-cc-view="${views}"${post.replace(/\shidden(?=[\s>]|$)/g, '')}${on ? '' : ' hidden'}>`;
  });
  if (analytics) c = c.replace('data-cc-category="analytics">', 'data-cc-category="analytics" checked>');
  /* a picture of the card, not the card: its controls are not reachable by Tab */
  c = c.replace(/<(button|input|a)\b/g, '<$1 tabindex="-1"');
  return c.split('\n').map(l => '                ' + l.trim()).join('\n');
}

