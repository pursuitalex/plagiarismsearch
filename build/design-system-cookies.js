/* ── splice: after Anti-patterns, before Sources of truth ─────────────────────── */
const s = html.indexOf(START);
const e = html.indexOf(END);
if (s >= 0 && e > s) {
  html = html.slice(0, s) + section + html.slice(e + END.length + 1);
} else {
  const at = html.indexOf('      <!-- ==================== SOURCES ==================== -->');
  if (at < 0) throw new Error('design-system.html: the SOURCES marker moved');
  html = html.slice(0, at) + section + '\n' + html.slice(at);
}

const navItem = '        <a href="#cookie-consent">Cookie consent</a>\n';
if (!html.includes(navItem)) {
  const after = '        <a href="#anti">Anti-patterns</a>\n';
  if (!html.includes(after)) throw new Error('design-system.html: the nav entries moved');
  html = html.replace(after, after + navItem);
}

fs.writeFileSync(FILE, html);
