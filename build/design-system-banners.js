/* The Banners section of site/design-system.html.

   design-system.html is hand-written, and that is fine for swatches and type ramps. It
   is not fine for the dark banners: each of them is rendered by code that lives in
   build/sections/ (banner.js, cta-band.js) and a hand-copied example would be a fourth
   version of the block, drifting like the other three did. So this script renders the examples with
   the same modules the pages use and splices the section in between two markers. Run
   it again and it replaces itself.

     node build/design-system-banners.js

   Three banners, in the order the system ranks them:

     1. the compact dark banner   build/sections/banner.js     between sections, one link onward
     2. the dark accent card      card recipe       a tall dark card with a double bezel
     3. the closing CTA band      build/sections/cta-band.js   last thing before the footer
*/
const fs = require('fs');
const path = require('path');
const banner = require('./sections/banner');
const cta = require('./sections/cta-band');

const FILE = path.join(__dirname, '..', 'site', 'design-system.html');
let html = fs.readFileSync(FILE, 'utf8');

const START = '      <!-- banners:start — generated by build/design-system-banners.js; do not edit by hand -->';
const END = '      <!-- banners:end -->';

/* ── the spec lines under each example ─────────────────────────────────────── */
const spec = rows => `        <dl class="grid sm:grid-cols-[9rem_1fr] gap-x-6 gap-y-2 text-[13.5px] leading-relaxed mb-5 sm:mb-6">
${rows.map(([k, v]) => `          <dt class="font-semibold text-ink-700">${k}</dt><dd class="text-ink-500 m-0"><code class="text-[12.5px] text-ink-700">${v}</code></dd>`).join('\n')}
        </dl>`;

/* ── 1 · the compact dark banner, rendered by build/sections/banner.js ─────────
   The showcase supplies its own rhythm and gutter: .ds-inset (build/assets/ds/ds.css)
   takes the section's own off. */
const compact = banner.section({
  id: 'ds-compact',
  glow: 'coral',
  eyebrow: 'Custom &amp; high volume',
  title: 'Need a custom or high-volume option?',
  lead: 'If the standard pricing options do not fit your checking volume or requirements, explore the available custom and high-volume options.',
  action: { label: 'Explore high-volume options', href: 'prices.html#high-volume' },
}).replace('class="banner"', 'class="banner ds-inset"');

/* ── 2 · the dark accent card, as Help Center sets it ──────────────────────── */
const accent = `        <div class="rounded-3xl sm:rounded-4xl lg:rounded-5xl bg-ink-950 text-white p-1.5 sm:p-2 ring-1 ring-white/10 shadow-diffuse-lg overflow-hidden">
          <div class="relative rounded-[18px] sm:rounded-3xl lg:rounded-[calc(2.5rem-0.5rem)] p-5 sm:p-8 lg:p-14 grid lg:grid-cols-[1.05fr_.95fr] gap-8 sm:gap-9 lg:gap-10 items-center overflow-hidden">
            <div class="orb w-[420px] h-[420px] bg-teal-500/15 -right-24 -top-40"></div>
            <div class="relative">
              <div class="text-[10px] sm:text-[10.5px] font-bold tracking-[0.22em] text-teal-300 mb-3">CONTACT US</div>
              <h2 class="text-[clamp(1.6rem,2.8vw,2.4rem)] font-extrabold tracking-tightest leading-[1.1] mb-4">Still stuck? Write to a human.</h2>
              <p class="text-[14.5px] sm:text-[15px] lg:text-[15.5px] text-white/60 leading-relaxed max-w-[50ch] mb-6 sm:mb-7 lg:mb-8">Feel free to contact our support team at any time and enjoy instant assistance — we are always happy to help you.</p>
              <div class="flex flex-wrap gap-3">
                <a href="help-center.html#contact" class="btn-press group inline-flex items-center gap-3 rounded-full h-12 sm:h-14 bg-white text-ink-900 text-[13.5px] sm:text-[14.5px] font-semibold pl-5 sm:pl-7 pr-2.5">
                  Email support
                  <span class="icon-orb w-9 h-9 rounded-full bg-ink-900/5 flex items-center justify-center">
                    <svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round"><path d="M5 12h14"/><path d="m12 5 7 7-7 7"/></svg>
                  </span>
                </a>
                <a href="help-center.html#contact" class="btn-press inline-flex items-center gap-2.5 rounded-full h-12 sm:h-14 px-5 sm:px-6 lg:px-7 text-[14px] sm:text-[15px] ring-1 ring-white/20 text-white font-semibold hover:bg-white/10 transition-colors duration-300">Live chat</a>
              </div>
            </div>
            <div class="relative hidden lg:block rounded-2xl bg-white/[.05] ring-1 ring-white/10 p-6 text-[13px] text-white/55 leading-relaxed">The right-hand cell is the page's: a form, a schematic, a list of channels. The card is the recipe; what it holds is not.</div>
          </div>
        </div>`;

/* ── 3 · the closing CTA band, drawn with the library template's own parts ─────
   (build/sections/cta-band.js). A showcase rendition: the band's classes, with the spec
   sheet's own frame, rhythm and gutter as utilities on top (a spec page may; a library
   section in a page may not). The button stands alone here, so it is inline. */
const band = `        <div class="cta-band rounded-3xl sm:rounded-4xl ring-1 ring-black/5 py-16 sm:py-20 lg:py-24">
${cta.background().split('\n').map(l => '          ' + l).join('\n')}
          <div class="cta-band-inner px-6">
            <h2 class="cta-title">${cta.ring('Try plagiarism checking before you choose a plan', 'before you choose')}</h2>
            <p class="cta-lead">Check up to 150 words without creating an account. See how the plagiarism checker works first, then return when you are ready to choose a plan.</p>
${cta.button({ label: 'Try a free plagiarism check', href: 'prices.html#free-check' }, ' inline-flex').split('\n').map(l => '            ' + l).join('\n')}
          </div>
        </div>`;

/* ── the section ───────────────────────────────────────────────────────────── */
const section = `${START}
      <section id="banners" class="py-16 border-t border-ink-100">
        <h2 class="text-[34px] font-extrabold tracking-tightest leading-tight mb-3">Banners</h2>
        <p class="text-[16px] text-ink-500 max-w-[62ch] mb-8 sm:mb-10 lg:mb-12">Three blocks, three jobs, three ranks. The two dark ones share a heading scale and a support colour and differ in composition — a short band against a tall double-bezel card; the closing band is light and takes the hero scale. The rules in DESIGN.md say which one a block is before it is drawn. The examples below are rendered by the same modules the pages use.</p>

        <h3 class="text-[22px] font-extrabold tracking-tightest mb-2">1 · Compact dark banner</h3>
        <p class="text-[15px] text-ink-500 max-w-[62ch] mb-4">Between sections. Says one thing about a capability that lives on another page and links there — API on the AI Detector page, AI checking on University, high volume on Pricing. A heading block, not a smaller act. With an aside panel the action sits under the text; without one, as here, the action takes the right-hand slot. <code class="text-[12.5px]">build/sections/banner.js</code></p>
${spec([
  ['box', 'rounded-3xl sm:rounded-4xl · px-6 py-8 sm:px-8 sm:py-9 lg:px-10 lg:py-10 · one orb top-right'],
  ['h2', 'text-[clamp(1.6rem,2.8vw,2.4rem)] font-extrabold tracking-tightest leading-[1.1] — shared with the dark accent card'],
  ['lead', '14.5 / 15 / 15.5 · text-white/60 (the heading-block ramp, the accent card colour)'],
  ['detail', '13 / 13.5 · text-white/50'],
  ['action', 'the white button, 13.5 / 14.5'],
])}
${compact}

        <h3 class="text-[22px] font-extrabold tracking-tightest mt-12 sm:mt-14 mb-2">2 · Dark accent card</h3>
        <p class="text-[15px] text-ink-500 max-w-[62ch] mb-4">A tall dark card inside a section: the recommended pricing tier, the Google Docs tile on the homepage, the contact block on Help Center. Double bezel, one orb, a two-cell body. Same heading and support colour as the compact banner; what makes it the accent card is the composition — the double bezel, the second cell, and the tall 48 / 56px buttons.</p>
${spec([
  ['shell', 'rounded-4xl|5xl bg-ink-950 ring-1 ring-white/10 shadow-diffuse-lg p-1.5 sm:p-2 · inner rounded-[calc(outer-0.5rem)]'],
  ['eyebrow', 'bare, text-teal-300, 10 / 10.5'],
  ['h2', 'text-[clamp(1.6rem,2.8vw,2.4rem)] font-extrabold tracking-tightest leading-[1.1]'],
  ['lead', '14.5 / 15 / 15.5 · text-white/60'],
  ['action', 'h-12 sm:h-14 · white primary, ring-white/20 secondary'],
])}
${accent}

        <h3 class="text-[22px] font-extrabold tracking-tightest mt-12 sm:mt-14 mb-2">3 · Closing CTA band</h3>
        <p class="text-[15px] text-ink-500 max-w-[62ch] mb-4">The last thing before the footer, on every page that has one. Light, not dark: a dot field under two masked glows, one ring mark in the heading, and the one place a non-hero heading takes the hero scale. Four parts and all four carry weight. <code class="text-[12.5px]">build/sections/cta-band.js</code></p>
${spec([
  ['ground', '#F2FCFC · SVG dot pattern 22px / 2px · warm glow upper-left, cool glow lower-right'],
  ['h2', 'text-[clamp(2.4rem,5.5vw,4.35rem)] font-extrabold tracking-tightest leading-[1.02] · one ring mark'],
  ['lead', '14.5 / 15 / 15.5 · text-ink-600 · max-w-[58ch] centred'],
  ['action', 'bg-ink-900, 15 / 16, with the icon orb'],
])}
${band}
      </section>
${END}
`;

/* ── splice ─────────────────────────────────────────────────────────────────── */
const s = html.indexOf(START);
const e = html.indexOf(END);
if (s >= 0 && e > s) {
  html = html.slice(0, s) + section + html.slice(e + END.length + 1);
} else {
  const at = html.indexOf('      <!-- ==================== 10 ICONS ==================== -->');
  if (at < 0) throw new Error('design-system.html: the ICONS marker moved');
  html = html.slice(0, at) + section + '\n' + html.slice(at);
}

/* the nav entry, once */
if (!html.includes('href="#banners"')) {
  html = html.replace('        <a href="#cards">Cards &amp; table</a>\n',
                      '        <a href="#cards">Cards &amp; table</a>\n        <a href="#banners">Banners</a>\n');
}

fs.writeFileSync(FILE, html);
console.log('  site/design-system.html — Banners section: 3 examples, nav entry');
