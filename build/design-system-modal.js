/* The Modal section of site/design-system.html.

   The popups are rendered by build/modal.js — the recipe the badge popup set — so the page
   shows the component, not a drawing of it. One example so far: the sign-up offer a guest
   meets on the way to the full report, restyled from the product's current popup.

     node build/design-system-modal.js

   Splices the section between two markers (after Checker states), its CSS between two
   more, and the nav entry once. Run it again and it replaces itself. */
const fs = require('fs');
const path = require('path');
const modal = require('./modal');

const FILE = path.join(__dirname, '..', 'site', 'design-system.html');
let html = fs.readFileSync(FILE, 'utf8');

const START = '      <!-- modal:start — generated by build/design-system-modal.js; do not edit by hand -->';
const END = '      <!-- modal:end -->';
const CSS_START = '  /* ===== modal — generated by build/design-system-modal.js ===== */';
const CSS_END = '  /* ===== /modal ===== */';

const S = modal.SIGNUP;
const body = modal.signup(S);

const dl = rows => `        <dl class="grid sm:grid-cols-[8rem_1fr] gap-x-6 gap-y-2 text-[13.5px] leading-relaxed">
${rows.map(([k, v]) => `          <dt class="font-semibold text-ink-700">${k}</dt><dd class="text-ink-500 m-0">${v}</dd>`).join('\n')}
        </dl>`;

/* a blurred report behind the inline example, so the card is judged where it appears */
const ghost = `            <div class="absolute inset-0 p-8 sm:p-12 space-y-3 blur-[3px] opacity-70" aria-hidden="true">
${[92, 100, 86, 97, 64, 100, 90, 78, 100, 83, 95, 70].map((w, i) => `              <div class="h-2.5 rounded-full ${i % 4 === 1 ? 'bg-orange-200' : 'bg-ink-200'}" style="width:${w}%"></div>`).join('\n')}
            </div>`;

const CHANGES = [
  ['Primary button', 'teal → the site’s dark pill (bg-ink-900). One primary colour for every call to action; teal stays the focus and link accent.'],
  ['Secondary button', 'square outline → white pill with a hairline ring, the same height (44px) as the primary. On phones the two stack, primary on top.'],
  ['Close', 'added. The current popup has no way out but Escape — a modal must always show one.'],
  ['Icon', 'teal disc → the rounded-2xl icon tile used across the site, Lucide lock-open.'],
  ['🎁 emoji', '→ Lucide gift in orange-600. Emoji icons are on the anti-patterns list.'],
  ['Bonus lines', 'two run-on lines with arrows → two offer rows: how you sign up, then what you get. Same words, the arrow dropped.'],
  ['Type', 'Manrope, heading 21 / 24 extrabold with the tight tracking, body 13.5 / 14.5 ink-600 — the badge popup’s scale.'],
];
const RULES = [
  ['Opens', 'on an action — pressing to see the full report — never on page load or on a timer.'],
  ['Focus', 'moves to the primary action on open, stays inside while open (Tab loops), and returns to the control that opened it.'],
  ['Closes', 'on the × button, a click on the backdrop, and Escape. The page behind does not scroll while it is open.'],
  ['Semantics', 'role="dialog", aria-modal="true", aria-labelledby on the heading. The close button is labelled “Close”.'],
  ['Size', 'max-width 440 for an offer, 560 for a task (the badge popup). Max height 88vh; the card scrolls, never the page.'],
  ['Motion', 'backdrop fades, card rises 8px and scales from .98 in 250ms; with reduced motion it only fades.'],
];

const section = `${START}
      <section id="modal" class="py-16 border-t border-ink-100">
        <h2 class="text-[34px] font-extrabold tracking-tightest leading-tight mb-3">Modal</h2>
        <p class="text-[16px] text-ink-500 max-w-[62ch] mb-8 sm:mb-10">One recipe for every popup, set by the badge popup: a dimmed, blurred backdrop and a white card with a close button. Rendered here by <code class="text-[13px]">build/modal.js</code>, the module the pages use.</p>

        <div class="flex flex-wrap items-center gap-2 mb-2">
          <h3 class="text-[22px] font-extrabold tracking-tightest mr-1">Sign-up offer · “See your full report”</h3>
          <span class="badge badge-sm" style="background:#FEF3C7;color:#92400E">Proposed</span>
          <span class="badge badge-sm bg-ink-100 text-ink-600">Product copy, unchanged</span>
        </div>
        <p class="text-[15px] text-ink-500 max-w-[62ch] mb-5">Shown to a guest who asks for more of the report than the free check gives. The popup the product shows today, put in the system’s type, buttons and icons; the words are the product’s own.</p>

        <div class="relative overflow-hidden rounded-3xl bg-white ring-1 ring-black/[.06] mb-4">
${ghost}
          <div class="relative bg-ink-950/60 backdrop-blur-sm flex items-center justify-center px-4 py-12 sm:py-16 lg:py-20">
            ${modal.card({ id: 'ds-md-inline', title: S.title, body })
              .replace('md-card ', '')  /* .md-card waits for .is-open to show; this one is always shown */
              .replace('<button type="button" data-close', '<button type="button" tabindex="-1" data-close')}
          </div>
        </div>
        <div class="flex flex-wrap items-center gap-3 mb-10 sm:mb-12">
          <button type="button" class="btn btn-sm btn-dark" data-modal-open="ds-md-signup">Open it for real</button>
          <span class="text-[13px] text-ink-500">Try Tab, Escape, and a click on the backdrop.</span>
        </div>

        <div class="grid lg:grid-cols-2 gap-8 lg:gap-12">
          <div>
            <h3 class="text-[18px] font-extrabold tracking-tightest mb-4">What changed from the current popup</h3>
${dl(CHANGES)}
          </div>
          <div>
            <h3 class="text-[18px] font-extrabold tracking-tightest mb-4">Behaviour</h3>
${dl(RULES)}
          </div>
        </div>

        <div class="mt-10 rounded-2xl bg-ink-50 px-5 py-4 text-[13.5px] leading-relaxed text-ink-600 max-w-[80ch]">
          <strong class="text-ink-900">Open questions.</strong>
          The heading and buttons are Title Case, the rest of the site sentence case (“See your full report”, “Sign up free”) — the copy is the product’s, so this is left to the owner of the copy.
          “Sign up now” in the lead and “Sign Up Free” go to the same place; the link could go, or become the secondary action.
          The checker’s inline sign-in gate (Checker states → Sign-in gate) and this popup do the same job — pick where each one is used, so a guest meets one of them, not both.
        </div>
${modal.shell({ id: 'ds-md-signup', title: S.title, body })}
        <script>${modal.script}
        </script>
      </section>
${END}
`;

const css = `${CSS_START}
${modal.style}
${CSS_END}`;

/* ── splice: after Checker states, else before Cards ──────────────────────────── */
const s = html.indexOf(START);
const e = html.indexOf(END);
if (s >= 0 && e > s) {
  html = html.slice(0, s) + section + html.slice(e + END.length + 1);
} else {
  const at = html.indexOf('      <!-- ==================== 09 CARDS + TABLE ==================== -->');
  if (at < 0) throw new Error('design-system.html: the CARDS marker moved');
  html = html.slice(0, at) + section + '\n' + html.slice(at);
}

const navItem = '        <a href="#modal">Modal</a>\n';
if (!html.includes(navItem)) {
  const after = ['        <a href="#checker-states">Checker states</a>\n', '        <a href="#controls">Controls</a>\n'].find(x => html.includes(x));
  if (!after) throw new Error('design-system.html: the nav entries moved');
  html = html.replace(after, after + navItem);
}

const cs = html.indexOf(CSS_START);
const ce = html.indexOf(CSS_END);
if (cs >= 0 && ce > cs) {
  html = html.slice(0, cs) + css + html.slice(ce + CSS_END.length);
} else {
  html = html.replace('</style>', css + '\n</style>');
}

fs.writeFileSync(FILE, html);
console.log('  site/design-system.html — Modal section: the sign-up offer, inline and live');
